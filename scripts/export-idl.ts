import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from './lib/common';

/**
 * Copies the Anchor IDL into the packages that use it and regenerates the
 * SDK's built-in deployments, so the SDK, app and node always match the
 * deployed program:
 *   - idl/soladb.json           (from target/idl/soladb.json after `anchor build`)
 *   - sdk/src/idl/soladb.json
 *   - sdk/src/deployments.ts    (from deployments/solana-{devnet,mainnet}.json)
 *
 * Usage: npm run export-idl
 */
const write = (file: string, content: string) => {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  console.log(`Wrote ${path.relative(ROOT, file)}`);
};

const built = path.join(ROOT, 'target', 'idl', 'soladb.json');
const committed = path.join(ROOT, 'idl', 'soladb.json');
if (fs.existsSync(built)) write(committed, fs.readFileSync(built, 'utf8'));
const idl = JSON.parse(fs.readFileSync(committed, 'utf8')) as { address: string };
write(path.join(ROOT, 'sdk', 'src', 'idl', 'soladb.json'), `${JSON.stringify(idl, null, 2)}\n`);

const declared = /declare_id!\("([^"]+)"\)/.exec(fs.readFileSync(path.join(ROOT, 'programs', 'soladb', 'src', 'lib.rs'), 'utf8'))?.[1];
if (declared !== idl.address) throw new Error(`IDL address ${idl.address} != declare_id ${declared}; rebuild the program`);

const deployments: Record<string, unknown> = {};
for (const cluster of ['devnet', 'mainnet']) {
  const file = path.join(ROOT, 'deployments', `solana-${cluster}.json`);
  if (!fs.existsSync(file)) continue;
  const d = JSON.parse(fs.readFileSync(file, 'utf8'));
  if (d.programId !== idl.address) throw new Error(`${file} is for program ${d.programId}, IDL is ${idl.address}`);
  deployments[cluster] = { cluster, rpcUrl: d.rpcUrl, programId: d.programId, deploySlot: d.deploySlot, nodes: d.nodes ?? [] };
}
write(
  path.join(ROOT, 'sdk', 'src', 'deployments.ts'),
  `// Generated by scripts/export-idl.ts from deployments/solana-*.json — do not edit.
import type { SolaDBDeployment } from './client';

export const DEPLOYMENTS: Record<string, SolaDBDeployment> = ${JSON.stringify(deployments, null, 2)};
`,
);
